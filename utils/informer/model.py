class Informer(nn.Module):
    def __init__(self, enc_in, dec_in, c_out, seq_len, label_len, out_len, 
                factor=5, d_model=512, n_heads=8, e_layers=3, d_layers=2, d_ff=512, 
                dropout=0.0, attn='prob', embed='fixed', freq='h', activation='gelu', 
                output_attention = False, distil=True, mix=True,
                device=torch.device('cuda:0')):
        super(Informer, self).__init__()
        self.pred_len = out_len
        self.attn = attn
        self.output_attention = output_attention

        # Encoding
        self.enc_embedding = DataEmbedding(enc_in, d_model, embed, freq, dropout)
        self.dec_embedding = DataEmbedding(dec_in, d_model, embed, freq, dropout)
        # Attention
        Attn = ProbAttention if attn=='prob' else FullAttention
        # Encoder
        self.encoder = Encoder(
            [
                EncoderLayer(
                    AttentionLayer(Attn(False, factor, attention_dropout=dropout, output_attention=output_attention), 
                                d_model, n_heads, mix=False),
                    d_model,
                    d_ff,
                    dropout=dropout,
                    activation=activation
                ) for l in range(e_layers)
            ],
            [
                ConvLayer(
                    d_model
                ) for l in range(e_layers-1)
            ] if distil else None,
            norm_layer=torch.nn.LayerNorm(d_model)
        )
        # Decoder
        self.decoder = Decoder(
            [
                DecoderLayer(
                    AttentionLayer(Attn(True, factor, attention_dropout=dropout, output_attention=False), 
                                d_model, n_heads, mix=mix),
                    AttentionLayer(FullAttention(False, factor, attention_dropout=dropout, output_attention=False), 
                                d_model, n_heads, mix=False),
                    d_model,
                    d_ff,
                    dropout=dropout,
                    activation=activation,
                )
                for l in range(d_layers)
            ],
            norm_layer=torch.nn.LayerNorm(d_model)
        )
        # self.end_conv1 = nn.Conv1d(in_channels=label_len+out_len, out_channels=out_len, kernel_size=1, bias=True)
        # self.end_conv2 = nn.Conv1d(in_channels=d_model, out_channels=c_out, kernel_size=1, bias=True)
        self.projection = nn.Linear(d_model, c_out, bias=True)
        
    def forward(self, x_enc, x_mark_enc, x_dec, x_mark_dec, 
                enc_self_mask=None, dec_self_mask=None, dec_enc_mask=None):
        enc_out = self.enc_embedding(x_enc, x_mark_enc)
        enc_out, attns = self.encoder(enc_out, attn_mask=enc_self_mask)

        dec_out = self.dec_embedding(x_dec, x_mark_dec)
        dec_out = self.decoder(dec_out, enc_out, x_mask=dec_self_mask, cross_mask=dec_enc_mask)
        dec_out = self.projection(dec_out)
        
        # dec_out = self.end_conv1(dec_out)
        # dec_out = self.end_conv2(dec_out.transpose(2,1)).transpose(1,2)
        if self.output_attention:
            return dec_out[:,-self.pred_len:,:], attns
        else:
            return dec_out[:,-self.pred_len:,:] # [B, L, D]


class TemporalInformerEncoderOnlyBlock(nn.Module):
    """
    Encoder-only Informer，用于 PAGInformer 中间层的时间特征提取。
    输出序列长度与输入相同（seq_len → seq_len）。
    """
    def __init__(
        self,
        channels,           # 输入通道数 (N * F)
        seq_len,            # 输入序列长度
        d_model=64,
        n_heads=4,
        e_layers=2,
        d_ff=128,
        dropout=0.1,
        attn='prob',
        embed='timeF',
        freq='h',
        activation='gelu',
        distil=True,
        output_attention=False,
        device=torch.device('cuda:0')
    ):
        super().__init__()
        self.seq_len = seq_len
        self.output_attention = output_attention

        # ==== 嵌入层 ====
        self.enc_embedding = DataEmbedding(channels, d_model, embed, freq, dropout)

        # ==== 注意力类型 ====
        Attn = ProbAttention if attn == 'prob' else FullAttention

        # ==== Encoder ====
        self.encoder = Encoder(
            [
                EncoderLayer(
                    AttentionLayer(
                        Attn(False, factor=5, attention_dropout=dropout, output_attention=output_attention),
                        d_model,
                        n_heads,
                        mix=False
                    ),
                    d_model,
                    d_ff,
                    dropout=dropout,
                    activation=activation
                ) for _ in range(e_layers)
            ],
            [
                ConvLayer(d_model)
                for _ in range(e_layers - 1)
            ] if distil else None,
            norm_layer=nn.LayerNorm(d_model)
        )

        # ==== 输出投影 ====
        self.projection = nn.Linear(d_model, channels, bias=True)

    def forward(self, x_enc, x_mark_enc, attn_mask=None):
        """
        输入:
            x_enc: [B, seq_len, channels]
            x_mark_enc: [B, seq_len, time_feature_dim]
        输出:
            out: [B, seq_len, channels]
        """
        # 编码阶段
        enc_out = self.enc_embedding(x_enc, x_mark_enc)  # [B, L, D_model]
        enc_out, attns = self.encoder(enc_out, attn_mask=attn_mask)  # [B, L, D_model]

        # 还原到原通道数
        out = self.projection(enc_out)  # [B, L, channels]

        if self.output_attention:
            return out, attns
        else:
            return out

